/**
 * scheduleSms — a nurse queues a text to be sent later (e.g. an appointment
 * reminder). It is NOT sent now: a pending ScheduledSms row is created and the
 * dispatchScheduledSms workflow picks it up when due, re-checking the sending
 * line, scoped consent and the agency kill switch at send time. The patient
 * only ever sees the agency's work number. PHI minimization: the body is never
 * written to the audit log.
 *
 * Released 2026-10-08 (owner decision). Authority, from protected sources only:
 *   - the caller is the protected platform owner, or a role-'user' account
 *     holding one active service-owned AgencyMembership (withTrustedClaims);
 *   - the SENDING number is never the caller's say-so: it must be an active,
 *     service-owned TelecomDestinationBinding with outbound SMS enabled, in
 *     the caller's agency. The caller's work number selects which binding when
 *     they have one; otherwise the agency's single outbound line is used;
 *   - consent is the scoped ledger for that binding (provider STOP wins), the
 *     same check sendSms applies, never a phone-only legacy row;
 *   - a linked patient must be in the caller's agency and either the caller is
 *     an agency administrator or manager, created the chart, or holds an
 *     active PatientCareTeamAssignment for it.
 */

const MIN_LEAD_MS = 60 * 1000;
const MAX_SCHEDULE_MS = 365 * 24 * 60 * 60 * 1000;
const ASSIGNMENT_SCAN_LIMIT = 10;

function normalizeE164(raw) {
  if (!raw) return null;
  const digits = String(raw).replace(/[^\d]/g, '');
  // Already-+ international is decided FIRST and never falls through to the NANP
  // branches. A 10-digit international number ("+49 89 123456") was otherwise
  // rewritten as an unrelated "+1..." US subscriber, which also slipped past the
  // +1-only international cost control. Mirrors src/components/voice/phoneUtils.js.
  if (String(raw).trim().startsWith('+')) {
    return digits.length >= 8 && digits.length <= 15 && digits[0] !== '0' ? `+${digits}` : null;
  }
  if (digits.length === 10) return `+1${digits}`;
  if (digits.length === 11 && digits.startsWith('1')) return `+${digits}`;
  return null;
}

function getThreadId(a, b) {
  const na = normalizeE164(a) || a;
  const nb = normalizeE164(b) || b;
  return [na, nb].sort().join('|');
}

/**
 * The one outbound SMS line for an agency, when the caller has no work number
 * of their own. Two or more lines are ambiguous and refuse.
 */
async function soleAgencyOutboundLine(base44, telnyxCreds, agencyId) {
  const rows = await base44.asServiceRole.entities.TelecomDestinationBinding.filter({
    provider: 'telnyx',
    integration_secret_id: telnyxCreds?.record?.id,
    messaging_profile_id: telnyxCreds?.messagingProfileId,
    agency_id: agencyId,
    status: 'active',
    sms_outbound_enabled: true,
  }, undefined, 3).catch(() => []);
  const lines = Array.isArray(rows)
    ? rows.filter((row) => row?.agency_id === agencyId && row?.status === 'active' && row?.sms_outbound_enabled === true)
    : [];
  return lines.length === 1 ? lines[0].destination_e164 : null;
}

async function hasActiveCareTeamAssignment(base44, agencyId, patientId, user) {
  const rows = await base44.asServiceRole.entities.PatientCareTeamAssignment.filter({
    agency_id: agencyId,
    patient_id: patientId,
    user_id: user.id,
    status: 'active',
  }, '-updated_date', ASSIGNMENT_SCAN_LIMIT).catch(() => []);
  const email = String(user.email || '').trim().toLowerCase();
  return Array.isArray(rows) && rows.some((row) => row?.agency_id === agencyId
    && row?.patient_id === patientId
    && row?.user_id === user.id
    && row?.status === 'active'
    && (row?.user_email_normalized == null || row.user_email_normalized === email));
}

Deno.serve(async (req) => {
  try {
    if (req.method !== 'POST') {
      return Response.json({ error: 'Method not allowed' }, { status: 405 });
    }
    const base44 = createClientFromRequest(userScopedClientRequest(req, PENNSYNC_PRODUCTION_APP_ID));
    const user = await withTrustedClaims(base44, await base44.auth.me());
    if (!user) return Response.json({ error: 'Unauthorized' }, { status: 401 });
    if (isDeactivatedUser(user)) return DEACTIVATED_USER_RESPONSE();
    if (user.disabled === true || user.is_service === true || user.is_verified === false) {
      return Response.json({ error: 'Forbidden' }, { status: 403 });
    }
    const owner = isProtectedSuperAdmin(user);
    // withTrustedClaims rebuilds agency_id / is_manager from the membership only
    // for a role 'user' profile; a built-in admin's copies are self-editable.
    const memberAgencyId = user.role === 'user' && claimIdentifier(user.agency_id) ? user.agency_id : null;
    if (!owner && !memberAgencyId) {
      return Response.json({
        error: 'An active agency membership is required to schedule texts.',
        code: 'agency_membership_required',
      }, { status: 403 });
    }
    // is_manager is true for a manager or agency_admin membership (withTrustedClaims).
    const agencyWide = owner || (!!memberAgencyId && user.is_manager === true);

    const body = await req.json().catch(() => null);
    if (!body || typeof body !== 'object' || Array.isArray(body)) {
      return Response.json({ error: 'Missing required fields: to_number, body, send_at' }, { status: 400 });
    }
    const { to_number, patient_id, send_at, template_label } = body;
    const messageBody = body.body;
    if (!to_number || !messageBody || !send_at) {
      return Response.json({ error: 'Missing required fields: to_number, body, send_at' }, { status: 400 });
    }
    if (typeof messageBody !== 'string' || messageBody.length === 0) {
      return Response.json({ error: 'Message body must be a non-empty string' }, { status: 400 });
    }
    if (messageBody.length > 1600) {
      return Response.json({ error: 'Message is too long (max 1600 characters).' }, { status: 400 });
    }
    if (patient_id != null && (typeof patient_id !== 'string' || !claimIdentifier(patient_id))) {
      return Response.json({ error: 'patient_id is invalid' }, { status: 400 });
    }
    if (template_label != null && (typeof template_label !== 'string' || template_label.length > 120)) {
      return Response.json({ error: 'template_label is invalid' }, { status: 400 });
    }

    const destination = normalizeE164(to_number);
    if (!destination) {
      return Response.json({ error: 'Invalid destination phone number' }, { status: 400 });
    }

    // Validate the requested time (mirrors src/components/messaging/scheduledSms.js).
    const t = new Date(send_at).getTime();
    const nowMs = Date.now();
    if (Number.isNaN(t)) return Response.json({ error: "That date/time isn't valid." }, { status: 400 });
    if (t < nowMs + MIN_LEAD_MS) return Response.json({ error: 'Pick a time at least a minute from now.' }, { status: 400 });
    if (t > nowMs + MAX_SCHEDULE_MS) return Response.json({ error: 'Pick a time within 365 days.' }, { status: 400 });
    const sendAtIso = new Date(t).toISOString();

    // The sending line comes from the service-owned binding, never from the
    // caller's profile alone.
    const telnyxCreds = await resolveTelnyxCreds(base44);
    let candidateLine = normalizeE164(user.work_phone_number);
    if (!candidateLine && memberAgencyId) {
      candidateLine = normalizeE164(await soleAgencyOutboundLine(base44, telnyxCreds, memberAgencyId));
    }
    if (!candidateLine) {
      return Response.json({
        error: 'No agency texting line is available to you. Ask an admin to assign your work number.',
        code: 'sms_line_unavailable',
      }, { status: 400 });
    }
    const smsAuthority = await resolveActiveTelnyxSmsBinding(base44, {
      integrationSecretId: telnyxCreds?.record?.id,
      integrationProvider: telnyxCreds?.record?.provider,
      integrationIsActive: telnyxCreds?.record?.is_active === true,
      messagingProfileId: telnyxCreds?.messagingProfileId,
      destinationE164: candidateLine,
      requireOutbound: true,
    });
    if (!smsAuthority.ok) {
      return Response.json({
        error: 'Scheduled texting is unavailable until your work number is an active, outbound-enabled agency line.',
        code: 'telecom_authority_migration_pending',
      }, { status: 503 });
    }
    if (memberAgencyId && smsAuthority.agencyId !== memberAgencyId) {
      return Response.json({ error: 'Your work number belongs to a different agency.' }, { status: 403 });
    }
    const agencyId = smsAuthority.agencyId;
    const fromNumber = smsAuthority.destinationE164;

    // TCPA: refuse to schedule without prior express consent on file in the
    // bound scope. The dispatcher re-checks at send time (unknown -> block).
    const scopedConsent = await loadLatestScopedSmsConsent(base44, smsAuthority, destination);
    if (!scopedConsent.ok) {
      return Response.json({
        error: 'SMS consent could not be verified in the bound tenant scope',
        reason: 'consent_scope_unavailable',
      }, { status: 503 });
    }
    if (scopedConsent.effectiveStatus === 'opted_out') {
      return Response.json({ error: 'This patient has opted out of text messages (replied STOP).' }, { status: 403 });
    }
    if (scopedConsent.effectiveStatus !== 'opted_in') {
      return Response.json({
        error: 'No texting consent is on file for this number. Record opt-in before scheduling.',
        reason: 'consent_required',
      }, { status: 403 });
    }

    // Authorize EVERY resolved chart (including phone matches) so a chart in
    // another agency, or one the caller does not care for, is never linked.
    const canAccessPatient = async (claimed) => {
      if (!claimed?.id || claimed.agency_id !== agencyId) return false;
      if (agencyWide) return true;
      if (claimed.created_by_user_id && claimed.created_by_user_id === user.id) return true;
      return hasActiveCareTeamAssignment(base44, agencyId, claimed.id, user);
    };

    let resolvedPatientId = null;
    const d = destination.replace(/[^\d]/g, '').slice(-10);
    if (d.length === 10) {
      const a = d.slice(0, 3), b = d.slice(3, 6), c = d.slice(6);
      const variants = [destination, `+1${d}`, `1${d}`, d, `(${a}) ${b}-${c}`, `${a}-${b}-${c}`];
      for (const variant of variants) {
        const matches = await base44.asServiceRole.entities.Patient
          .filter({ phone: variant, agency_id: agencyId }, undefined, 10).catch(() => []);
        for (const match of matches || []) {
          if (await canAccessPatient(match)) {
            resolvedPatientId = match.id;
            break;
          }
        }
        if (resolvedPatientId) break;
      }
    }
    if (patient_id) {
      if (resolvedPatientId && resolvedPatientId !== patient_id) {
        return Response.json({
          error: 'patient_id does not match the destination phone number',
          reason: 'patient_phone_mismatch',
        }, { status: 400 });
      }
      if (!resolvedPatientId) {
        const [claimed] = await base44.asServiceRole.entities.Patient
          .filter({ id: patient_id }, '', 1).catch(() => []);
        if (!claimed || claimed.id !== patient_id) {
          return Response.json({ error: 'Patient not found' }, { status: 404 });
        }
        if (!(await canAccessPatient(claimed))) {
          return Response.json({ error: 'Forbidden' }, { status: 403 });
        }
        resolvedPatientId = patient_id;
      }
    }

    const row = await base44.asServiceRole.entities.ScheduledSms.create({
      to_number: destination,
      from_number: fromNumber,
      body: messageBody,
      patient_id: resolvedPatientId || null,
      nurse_email: user.email,
      thread_id: getThreadId(fromNumber, destination),
      send_at: sendAtIso,
      status: 'pending',
      template_label: template_label || null,
      attempts: 0,
      created_by: user.email,
    });

    await base44.asServiceRole.entities.UserActivity.create({
      user_email: user.email,
      user_name: user.full_name,
      action: 'sms_scheduled',
      entity_type: 'ScheduledSms',
      entity_id: row.id,
      details: {
        provider: 'telnyx',
        direction: 'outbound',
      },
      status: 'success',
    }).catch(() => console.error('scheduleSms: activity log failed'));

    return Response.json({ success: true, scheduled_id: row.id, send_at: sendAtIso });
  } catch {
    console.error('scheduleSms failed');
    return Response.json({ error: 'Internal server error' }, { status: 500 });
  }
});
