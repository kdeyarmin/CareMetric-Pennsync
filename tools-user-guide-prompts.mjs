#!/usr/bin/env node
/**
 * The user-guide prompts, lifted from the Base44 original rather than retyped.
 *
 * `generateUserGuidePDF` carries about 480 lines of prompt text across eleven
 * guide types. That text is the contract with the model, so a port has to
 * reproduce it exactly — and hand-copying 480 lines is a transcription exercise
 * with no upside. The parity test already caught a single dropped trailing
 * space in a much shorter prompt, which is the argument for not doing this by
 * hand at all.
 *
 * So the prompts are extracted: this drives the original module with its client
 * and its PDF library stubbed, captures the exact argument each guide type
 * produces, and writes them to a committed data module. The port then looks up
 * a prompt instead of assembling one, and the parity test compares the whole
 * call against the original — so the committed data cannot drift from the
 * source it came from without failing.
 *
 * Regenerate with `node tools-user-guide-prompts.mjs --write`.
 */
import { readFileSync, writeFileSync, unlinkSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { transpileTs } from './tools-transpile-ts.mjs';

export const ORIGINAL = 'base44/functions/generateUserGuidePDF/entry.ts';
export const PROMPTS_FILE = 'services/pennsync-api/user-guide-prompts.mjs';
/** Every guide type the original answers for, in the order it declares them. */
export const GUIDE_TYPES = Object.freeze(['referral_intake', 'admission_documentation', 'smart_notes',
  'oasis_assessment', 'care_plans', 'patient_management', 'training_hub', 'compliance_quality',
  'messages', 'patient_alerts', 'all_features']);
/** What an unknown or crafted guide type resolves to, as the original resolves it. */
export const DEFAULT_GUIDE_TYPE = 'all_features';

const CAPTURED = Symbol('captured');

/** Load the original's handler with its client and PDF library replaced. */
async function loadOriginal(repository) {
  let source = readFileSync(join(repository, ORIGINAL), 'utf8');
  source = source.replace(/import\s+\{\s*jsPDF\s*\}\s+from\s+'npm:jspdf@[^']*';?/, 'const jsPDF = class {};');
  source = source.replace(/import\s+\{[^}]*\}\s+from\s+'npm:[^']*';?/,
    `const createClientFromRequest = () => ({
       auth: { me: async () => ({ id: 'extractor', is_active: true }) },
       integrations: { Core: { InvokeLLM: async (argument) => {
         globalThis.__guidePrompt = argument.prompt;
         globalThis.__guideSchema = argument.response_json_schema;
         const stop = new Error('captured'); stop.captured = true; throw stop;
       } } },
     });`);
  const js = transpileTs(source).outputText;
  const file = join(tmpdir(), `guideprompts_${Date.now()}_${Math.random().toString(36).slice(2)}.mjs`);
  let handler = null;
  const previous = globalThis.Deno;
  globalThis.Deno = { ...(previous ?? {}), serve: fn => { handler = fn; }, env: { get: () => undefined } };
  writeFileSync(file, js);
  try { await import(pathToFileURL(file).href); }
  finally { try { unlinkSync(file); } catch { /* already gone */ } globalThis.Deno = previous; }
  if (!handler) throw new Error('GUIDE_ORIGINAL_REGISTERED_NO_HANDLER');
  return handler;
}

/** The exact prompt and schema the original sends for one guide type. */
export async function capture(handler, guideType) {
  globalThis.__guidePrompt = undefined;
  globalThis.__guideSchema = undefined;
  // The original logs the sentinel through its own catch. That is its normal
  // behaviour, not a fault here, so it is silenced rather than printed.
  const noise = console.error;
  console.error = () => {};
  try {
  await handler(new Request('https://synthetic.invalid/', {
    method: 'POST', headers: { 'content-type': 'application/json' },
    body: JSON.stringify({ guide_type: guideType }),
  }));
  } finally { console.error = noise; }
  const prompt = globalThis.__guidePrompt;
  if (typeof prompt !== 'string' || !prompt) throw new Error(`GUIDE_PROMPT_NOT_CAPTURED:${guideType}`);
  return { prompt, schema: globalThis.__guideSchema };
}

export async function extractPrompts(repository) {
  const handler = await loadOriginal(repository);
  const prompts = {};
  let schema = null;
  for (const guideType of GUIDE_TYPES) {
    const captured = await capture(handler, guideType);
    prompts[guideType] = captured.prompt;
    schema = schema ?? captured.schema;
  }
  return { prompts, schema, [CAPTURED]: true };
}

export function renderModule({ prompts, schema }) {
  const literal = value => JSON.stringify(value);
  const entries = GUIDE_TYPES.map(type => `  ${type}: ${literal(prompts[type])},`).join('\n');
  return `// GENERATED by \`node tools-user-guide-prompts.mjs --write\`. Do not edit by hand.
//
// The prompts \`base44/functions/generateUserGuidePDF\` sends, one per guide
// type, captured from the original rather than retyped: the text is the
// contract with the model, and 480 lines of it is a transcription exercise with
// no upside. \`pennsyncApiIntegrationParity.test.js\` drives the original and
// this port with the same input and compares the whole call, so this file
// cannot drift from its source without failing.
export const DEFAULT_GUIDE_TYPE = ${literal(DEFAULT_GUIDE_TYPE)};

export const USER_GUIDE_PROMPTS = Object.freeze({
${entries}
});

/**
 * An unknown or crafted guide type resolves to the default, exactly as the
 * original resolves it. It matters beyond tidiness: the resolved value flows
 * into the download filename, so an unresolved one could mislabel the file or
 * reach the Content-Disposition header.
 */
export const resolveGuideType = guideType =>
  (Object.hasOwn(USER_GUIDE_PROMPTS, guideType) ? guideType : DEFAULT_GUIDE_TYPE);

export const USER_GUIDE_SCHEMA = Object.freeze(${JSON.stringify(schema, null, 2)});
`;
}

export async function main(args = process.argv.slice(2),
  { repository = resolve(dirname(fileURLToPath(import.meta.url))), log = console.log, write = writeFileSync } = {}) {
  if (args.some(argument => !['--write', '--summary'].includes(argument))) {
    log(JSON.stringify({ error: 'INVALID_ARGUMENTS' }));
    return 2;
  }
  let extracted;
  try { extracted = await extractPrompts(repository); }
  catch (error) { log(JSON.stringify({ error: error?.message || 'GUIDE_PROMPTS_UNAVAILABLE' })); return 2; }
  const module = renderModule(extracted);
  if (args.includes('--write')) {
    write(join(repository, PROMPTS_FILE), module);
    log(JSON.stringify({ updated: PROMPTS_FILE, guides: GUIDE_TYPES.length, bytes: module.length }));
    return 0;
  }
  const committed = readFileSync(join(repository, PROMPTS_FILE), 'utf8');
  const matches = committed === module;
  log(`user guide prompts ${matches ? 'unchanged' : 'CHANGED'}: ${GUIDE_TYPES.length} guides`);
  return matches ? 0 : 1;
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
  main().then(code => { process.exitCode = code; });
}
